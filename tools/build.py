"""Generate checklists from catalog/capabilities.yaml.

    python tools/build.py                  # regenerate checklists/ and client-template/scorecard.yaml
    python tools/build.py --client <dir>   # sync <dir>/scorecard.yaml with the catalog, write <dir>/scorecard.md
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "catalog" / "capabilities.yaml"
TABLES = ROOT / "catalog" / "data-tables.yaml"
OUT = ROOT / "checklists"
TEMPLATE = ROOT / "client-template"

IMPACT = {"H": 3, "M": 2, "L": 1}
EFFORT = {"L": 3, "M": 2, "H": 1}  # low effort sorts first

BUCKETS = [
    ("Quick wins: high impact, low effort", lambda c: c["impact"] == "H" and c["effort"] == "L"),
    ("Big bets: high impact, more effort", lambda c: c["impact"] == "H"),
    ("Fill-ins: medium impact, low effort", lambda c: c["impact"] == "M" and c["effort"] == "L"),
    ("Later", lambda c: True),
]

TYPES = [
    ("foundation", "Foundations (Tier 0)"),
    ("action", "Response actions (build once, reused by every trigger)"),
    ("auto-response", "Automated responses and their triggers (Tier 1)"),
    ("triage-detection", "Detections for the triage agent (Tier 2)"),
    ("auto-investigation", "Automatic investigations"),
    ("manual-action", "Manual actions (pre-staged runbooks)"),
    ("hardening", "Hardening"),
]

VECTORS = [
    ("pulled", "Pulled in"),
    ("pushed", "Pushed in"),
    ("walked", "Walked in"),
    ("post-access", "Post-access"),
]

STATUSES = ["todo", "in-progress", "done", "n/a"]
HEADER = "<!-- Generated by tools/build.py from catalog/. Do not edit by hand. -->\n\n"


def load():
    caps = yaml.safe_load(CATALOG.read_text(encoding="utf-8"))["capabilities"]
    ids = [c["id"] for c in caps]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        sys.exit(f"Duplicate capability ids: {sorted(dupes)}")
    names = {c["id"]: c["name"] for c in caps}
    for c in caps:
        if c["impact"] not in IMPACT or c["effort"] not in EFFORT:
            sys.exit(f"{c['id']}: impact/effort must be H/M/L")
        for ref in c.get("uses", []):
            if ref not in names or not ref.startswith("ACT-"):
                sys.exit(f"{c['id']}: uses unknown action {ref}")
        c["uses_names"] = [f"{names[ref]} ({ref})" for ref in c.get("uses", [])]
    return caps


def priority(c):
    return (-IMPACT[c["impact"]], -EFFORT[c["effort"]], c["tier"], c["id"])


def bucket(c):
    return next(name for name, test in BUCKETS if test(c))


def line(c, check=True):
    box = "- [ ] " if check else "- "
    return f"{box}**{c['id']}** {c['name']} · _{c['impact']} impact / {c['effort']} effort · Tier {c['tier']}_"


def detail(c):
    out = [line(c)]
    for key, label in [("trigger", "Trigger"), ("action", "Action"), ("guardrails", "Guardrails"), ("done_when", "Done when")]:
        if c.get(key):
            out.append(f"  - {label}: {' '.join(str(c[key]).split())}")
        if key == "action" and c["uses_names"]:
            out.append(f"  - Uses actions: {', '.join(c['uses_names'])}")
    return "\n".join(out)


def table(caps):
    rows = ["| ID | Capability | Type | Tier | Impact | Effort | Vectors | Baseline |", "|---|---|---|---|---|---|---|---|"]
    for c in caps:
        rows.append(
            f"| {c['id']} | {c['name']} | {c['type']} | {c['tier']} | {c['impact']} | {c['effort']} "
            f"| {', '.join(c['vectors'])} | {'✓' if c.get('baseline') else ''} |"
        )
    return "\n".join(rows)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")


def build_baseline(caps):
    base = sorted((c for c in caps if c.get("baseline")), key=priority)
    parts = [
        HEADER,
        "# Baseline Checklist: \"basics done\"\n\n",
        f"{len(base)} capabilities every company should have, ordered by impact then effort. ",
        "See [PLAN.md](../PLAN.md) for phasing.\n",
    ]
    for name, _ in BUCKETS:
        group = [c for c in base if bucket(c) == name]
        if group:
            parts.append(f"\n## {name}\n\n" + "\n".join(detail(c) for c in group) + "\n")
    write(OUT / "baseline.md", "".join(parts))


def build_priority(caps):
    parts = [HEADER, "# All Capabilities by Priority\n\n✓ = part of the baseline.\n"]
    for name, _ in BUCKETS:
        group = sorted((c for c in caps if bucket(c) == name), key=priority)
        if group:
            parts.append(f"\n## {name}\n\n{table(group)}\n")
    write(OUT / "by-priority.md", "".join(parts))


def build_by_type(caps):
    parts = [HEADER, "# Capabilities by Type\n\nWithin each type, ordered by impact then effort.\n"]
    for key, title in TYPES:
        group = sorted((c for c in caps if c["type"] == key), key=priority)
        if group:
            parts.append(f"\n## {title}\n\n" + "\n".join(detail(c) for c in group) + "\n")
    write(OUT / "by-type.md", "".join(parts))


def build_by_vector(caps):
    parts = [
        HEADER,
        "# Coverage by Attack Vector\n\n",
        "Pulled in = user/agent brings it in. Pushed in = exploited service. ",
        "Walked in = valid access. Post-access = what they do once in, whatever the vector.\n\n",
        "| Vector | Baseline | Total |\n|---|---|---|\n",
    ]
    for key, title in VECTORS:
        group = [c for c in caps if key in c["vectors"]]
        parts.append(f"| {title} | {sum(1 for c in group if c.get('baseline'))} | {len(group)} |\n")
    ai = [c for c in caps if c.get("ai")]
    parts.append(f"| Attacks on your own AI | {sum(1 for c in ai if c.get('baseline'))} | {len(ai)} |\n")
    for key, title in VECTORS:
        group = sorted((c for c in caps if key in c["vectors"]), key=priority)
        parts.append(f"\n## {title}\n\n" + "\n".join(line(c, check=False) for c in group) + "\n")
    parts.append(
        "\n## Attacks on your own AI\n\nPrompt-injected agents, malicious MCP servers, agents acting outside their lane. "
        "A pulled-in path where the AI agent is the one that brings it in.\n\n"
        + "\n".join(line(c, check=False) for c in sorted(ai, key=priority))
        + "\n"
    )
    write(OUT / "by-vector.md", "".join(parts))


def sync_scorecard(caps, path, client_name):
    existing = {}
    if path.exists():
        existing = (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("capabilities", {}) or {}
    lines = [
        f"# Scorecard for {client_name}. Status: {' | '.join(STATUSES)}",
        "# Generated entries are added by tools/build.py; edit status and notes by hand.",
        "capabilities:",
    ]
    for c in sorted(caps, key=lambda c: c["id"]):
        entry = existing.get(c["id"]) or {}
        status = entry.get("status", "todo")
        if status not in STATUSES:
            sys.exit(f"{path}: {c['id']} has invalid status '{status}'")
        notes = entry.get("notes", "")
        lines.append(f"  {c['id']}:  # {c['name']}")
        lines.append(f"    status: {status}")
        lines.append(f"    notes: {yaml.safe_dump(notes, default_style=None).strip().removesuffix('...').strip()}")
    write(path, "\n".join(lines) + "\n")
    return {cid: (existing.get(cid) or {}) for cid in (c["id"] for c in caps)}


def build_client(caps, client_dir):
    client_dir = Path(client_dir).resolve()
    profile = client_dir / "profile.yaml"
    name = client_dir.name
    if profile.exists():
        name = (yaml.safe_load(profile.read_text(encoding="utf-8")) or {}).get("client") or name
    scores = sync_scorecard(caps, client_dir / "scorecard.yaml", name)
    status = {cid: s.get("status", "todo") for cid, s in scores.items()}

    def pct(group):
        group = [c for c in group if status[c["id"]] != "n/a"]
        done = sum(1 for c in group if status[c["id"]] == "done")
        return f"{done}/{len(group)} ({100 * done // len(group) if group else 100}%)"

    base = [c for c in caps if c.get("baseline")]
    parts = [
        f"<!-- Generated by tools/build.py. Edit scorecard.yaml, not this file. -->\n\n# {name}: Agentic Defence Scorecard\n\n",
        f"**Basics done:** {pct(base)} &nbsp;·&nbsp; **All capabilities:** {pct(caps)}\n\n",
        "| Vector | Baseline done |\n|---|---|\n",
    ]
    for key, title in VECTORS:
        parts.append(f"| {title} | {pct([c for c in base if key in c['vectors']])} |\n")
    parts.append(f"| Attacks on your own AI | {pct([c for c in base if c.get('ai')])} |\n")
    parts.append(f"| Response actions ready | {pct([c for c in base if c['type'] == 'action'])} |\n")
    parts.append("\n## Next up (baseline, by priority)\n\n")
    todo = sorted((c for c in base if status[c["id"]] in ("todo", "in-progress")), key=priority)
    for c in todo:
        mark = " _(in progress)_" if status[c["id"]] == "in-progress" else ""
        parts.append(line(c) + mark + "\n")
    if not todo:
        parts.append("Baseline complete. Move on to the framework's checklists/by-priority.md items.\n")
    write(client_dir / "scorecard.md", "".join(parts))


TABLE_PRIORITIES = [
    ("tier1-dependency", "Tier 1 dependencies: automation reads these before acting, so build them first"),
    ("tier2-context", "Tier 2 context: detections and the triage agent need these"),
    ("later", "Later: the remaining 20%"),
]

MAINTENANCE_MODEL = """\
## How tables are maintained

**Scripts build, agents propose, humans approve, automation reads.**

| Who | Does | Never does |
|---|---|---|
| **Deterministic script** | Pulls from the authoritative sources on a schedule, applies fixed rules, writes the table, flags diffs and stale rows | Guess. Anything the rules can't classify goes to the agent |
| **AI agent** | Classifies what the rules couldn't, researches new items, drafts owner questions, explains diffs | Write to a table directly. It submits proposals |
| **Human** | Approves proposals and periodically re-attests | Hand-maintain anything a script can pull |
| **Automation** | Reads the runtime copy at action time | Act on a missing or stale row without falling back to the safe default |

Rules for every table:
- [ ] **Tightening is automatic, loosening needs a human.** A script or agent may move a host from C to B or remove an exception on its own; moving to C or adding an exception needs approval.
- [ ] **Every row has a source and a last-seen or last-reviewed date.** Rows past their refresh window count as missing.
- [ ] **Every table has a safe default** for missing rows, and automation uses it.
- [ ] **Health is monitored:** last refresh time, row count change, and % of hosts/identities with no row. A table that stops refreshing is an alert.
- [ ] **Every table has one store of record with a change history** (who changed what, when, why). Automation reads a runtime copy (SIEM lookup, EDR tag, IdP group) kept in sync from it.
"""


def load_tables(caps):
    tables = yaml.safe_load(TABLES.read_text(encoding="utf-8"))["tables"]
    names = {c["id"]: c["name"] for c in caps} | {t["id"]: t["name"] for t in tables}
    for t in tables:
        if t["priority"] not in dict(TABLE_PRIORITIES):
            sys.exit(f"{t['id']}: unknown priority {t['priority']}")
        for ref in t.get("used_by", []):
            if ref not in names:
                sys.exit(f"{t['id']}: used_by unknown id {ref}")
        t["used_by_names"] = [f"{names[ref]} ({ref})" for ref in t.get("used_by", [])]
    return tables


def build_tables(tables):
    parts = [
        HEADER,
        "# Reference Data Tables\n\n",
        "The lookups that detections and automation read at run time. If these are wrong or stale, ",
        "automation either can't act or acts on the wrong thing. Source: `catalog/data-tables.yaml`.\n\n",
        MAINTENANCE_MODEL,
        "\n## Summary\n\n| Table | Priority | Baseline | Refresh | Safe default when missing |\n|---|---|---|---|---|\n",
    ]
    for key, _ in TABLE_PRIORITIES:
        for t in (t for t in tables if t["priority"] == key):
            parts.append(
                f"| **{t['name']}** ({t['id']}) | {key} | {'✓' if t.get('baseline') else ''} "
                f"| {t['refresh']} | {t['safe_default']} |\n"
            )
    for key, title in TABLE_PRIORITIES:
        group = [t for t in tables if t["priority"] == key]
        if not group:
            continue
        parts.append(f"\n## {title}\n")
        for t in group:
            parts.append(f"\n### {t['name']} ({t['id']})\n\n{' '.join(t['purpose'].split())}\n\n")
            parts.append(f"- **Sources:** {', '.join(t['sources'])}\n")
            for key2, label in [("script", "Script"), ("agent", "AI agent"), ("human", "Human")]:
                parts.append(f"- **{label}:** {' '.join(str(t[key2]).split())}\n")
            parts.append(f"- **Refresh:** {t['refresh']} · **Safe default:** {t['safe_default']}\n")
            parts.append(f"- **Columns:** {', '.join(t['columns'])}\n")
            parts.append(f"- **Used by:** {', '.join(t['used_by_names'])}\n")
    write(OUT / "data-tables.md", "".join(parts))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--client", help="client folder containing profile.yaml / scorecard.yaml")
    args = ap.parse_args()
    caps = load()
    if args.client:
        build_client(caps, args.client)
        return
    build_baseline(caps)
    build_priority(caps)
    build_by_type(caps)
    build_by_vector(caps)
    build_tables(load_tables(caps))
    sync_scorecard(caps, TEMPLATE / "scorecard.yaml", "<client>")


if __name__ == "__main__":
    main()
